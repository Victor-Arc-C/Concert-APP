type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : T extends (...args: infer A) => infer R
      ? (...args: A) => Widen<R>
      : T extends Record<string, unknown>
        ? { [K in keyof T]: Widen<T[K]> }
        : T;
